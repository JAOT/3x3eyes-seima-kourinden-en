# Tiles do BG3 usados só pelos kana (podem ser substituídos). Segmentos contínuos: (primeiro tile, nº de tiles)
SEGMENTS = [(0x036, 42), (0x06C, 26), (0x087, 27), (0x173, 40), (0x12B, 21), (0x143, 18), (0x156, 16)]
BLANK_TILE = 0x0D3       # tile vazio (fundo da janela), usado no espaço
TILE_ATTR = 0x2400       # prioridade + paleta 1, igual aos kana


def glyph_rows(ch):
    rows = G[ch]
    assert len(rows) <= 12, ch
    for r in rows:
        assert len(r) == 6, (ch, r)
    cell = ['........'] * 16
    for i, r in enumerate(rows):
        cell[2 + i] = '.' + r + '.'
    return cell


def tile_2bpp(rows8):
    """8 linhas de 8 píxeis -> 16 bytes 2bpp. Fundo = cor 1, letra = cor 2."""
    out = bytearray()
    for r in rows8:
        ink = sum(1 << (7 - x) for x, c in enumerate(r) if c == '#')
        out.append(~ink & 0xFF)   # plano 0: fundo
        out.append(ink)           # plano 1: letra
    return bytes(out)


def build():
    tiles_avail = [t for first, n in SEGMENTS for t in range(first, first + n)]
    chars = [chr(c) for c in range(0x21, 0x7F)]          # o espaço usa o tile vazio
    assert 2 * len(chars) <= len(tiles_avail)
    gfx = {}
    glyph_map = {' ': (BLANK_TILE, BLANK_TILE)}
    for i, ch in enumerate(chars):
        top, bot = tiles_avail[2 * i], tiles_avail[2 * i + 1]
        cell = glyph_rows(ch)
        gfx[top] = tile_2bpp(cell[0:8])
        gfx[bot] = tile_2bpp(cell[8:16])
        glyph_map[ch] = (top, bot)
    # dados de tiles pela ordem dos segmentos (tiles sem glifo ficam vazios)
    blank = tile_2bpp(['........'] * 8)
    data = bytearray()
    seg_asm = []
    for first, n in SEGMENTS:
        off = len(data)
        for t in range(first, first + n):
            data += gfx.get(t, blank)
        # endereço relativo à base de caracteres do BG3 (somada no NMI: $3000 no campo, $2000 no combate)
        seg_asm.append(f'    dw ${first * 8:04X}, FontGfx+${off:04X}, ${n * 16:04X}, 0')
    lines = ['; gerado por fonte_en.py - não editar', 'GlyphMap:   ; ASCII $20-$7E: tile de cima, tile de baixo']
    for c in range(0x20, 0x7F):
        top, bot = glyph_map[chr(c)]
        lines.append(f'    dw ${TILE_ATTR | top:04X}, ${TILE_ATTR | bot:04X}   ; {chr(c)!r}')
    lines.append('FontSegs:   ; endereço VRAM relativo à base do BG3 (palavra), origem, tamanho, 0')
    lines += seg_asm
    return bytes(data), '\n'.join(lines) + '\n'


if __name__ == '__main__':
    outdir = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else '.')
    data, asm = build()
    (outdir / 'font_en.bin').write_bytes(data)
    (outdir / 'font_en.asm').write_text(asm, encoding='utf-8')
    # defines por carácter (código ASCII em hex): !GT_xx = tile de cima, !GB_xx = tile de baixo
    tiles_avail = [t for first, n in SEGMENTS for t in range(first, first + n)]
    defs = [f'!FontSegCount = {len(SEGMENTS)}']
    for c in range(0x20, 0x7F):
        if c == 0x20:
            top = bot = BLANK_TILE
        else:
            k = c - 0x21
            top, bot = tiles_avail[2 * k], tiles_avail[2 * k + 1]
        defs.append(f'!GT_{c:02X} = ${TILE_ATTR | top:04X}')
        defs.append(f'!GB_{c:02X} = ${TILE_ATTR | bot:04X}')
    (outdir / 'font_en_defs.asm').write_text('\n'.join(defs) + '\n', encoding='utf-8')
    print(f'font_en.bin: {len(data)} bytes; {len(SEGMENTS)} segmentos')
